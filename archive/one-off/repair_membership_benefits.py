#!/usr/bin/env python3
"""Apply (or dry-run) membership benefits repairs from a manifest.

Reads output/membership_benefits_repairs.json + membership_audit_snapshot.json.
--dry-run: print before/after diffs and counts.
--apply: write guarded SQL with optimistic updated_at checks.

Usage:
  python3 one-off/repair_membership_benefits.py --dry-run
  python3 one-off/repair_membership_benefits.py --apply
  python3 one-off/repair_membership_benefits.py --apply --plan-ids 242,247
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any, Optional

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_MANIFEST = ROOT / "output" / "membership_benefits_repairs.json"
DEFAULT_SNAPSHOT = ROOT / "output" / "membership_audit_snapshot.json"
DEFAULT_SQL = ROOT / "output" / "membership_benefits_repair_apply.sql"


def sql_quote(s: Optional[str]) -> str:
    if s is None:
        return "NULL"
    return "'" + str(s).replace("'", "''") + "'"


def jsonb_array(benefits: list[str]) -> str:
    return sql_quote(json.dumps(benefits, ensure_ascii=False)) + "::jsonb"


def load_snapshot_index(path: Path) -> dict[int, dict[str, Any]]:
    data = json.loads(path.read_text(encoding="utf-8"))
    rows = data["rows"] if isinstance(data, dict) else data
    return {int(r["plan_id"]): r for r in rows}


def load_manifest(path: Path) -> list[dict[str, Any]]:
    data = json.loads(path.read_text(encoding="utf-8"))
    if isinstance(data, dict):
        return list(data.get("repairs") or data.get("items") or [])
    return list(data)


def diff_lists(old: list[str], new: list[str]) -> dict[str, list[str]]:
    old_set = set(old)
    new_set = set(new)
    return {
        "removed": sorted(old_set - new_set),
        "added": sorted(new_set - old_set),
        "unchanged": sorted(old_set & new_set),
    }


def build_update_sql(item: dict[str, Any], snap: dict[str, Any]) -> str:
    plan_id = int(item["plan_id"])
    updated_at = snap.get("updated_at")
    if not updated_at:
        raise ValueError(f"plan {plan_id}: missing snapshot updated_at")

    action = item["action"]
    new_benefits = item.get("new_benefits")
    if new_benefits is None:
        new_benefits = []
    if not isinstance(new_benefits, list):
        raise ValueError(f"plan {plan_id}: new_benefits must be list")

    new_source = item.get("new_source_url")
    source_clause = ""
    if new_source and new_source != (item.get("old_source_url") or snap.get("source_url")):
        source_clause = f",\n  source_url = {sql_quote(new_source)}"

    # Keep offers in sync later: mark not extracted after benefit change
    return f"""-- plan_id={plan_id} action={action} reason={item.get('reason','')}
UPDATE public.clinic_memberships
SET
  benefits = {jsonb_array(new_benefits)},
  is_offer_extracted = false,
  updated_at = now(){source_clause}
WHERE plan_id = {plan_id}
  AND updated_at = {sql_quote(updated_at)}::timestamptz;
"""


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--manifest", type=Path, default=DEFAULT_MANIFEST)
    ap.add_argument("--snapshot", type=Path, default=DEFAULT_SNAPSHOT)
    ap.add_argument("--sql-out", type=Path, default=DEFAULT_SQL)
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--apply", action="store_true")
    ap.add_argument("--plan-ids", default="", help="comma-separated filter")
    args = ap.parse_args()

    if not args.dry_run and not args.apply:
        args.dry_run = True

    snap_idx = load_snapshot_index(args.snapshot)
    repairs = load_manifest(args.manifest)
    if args.plan_ids:
        want = {int(x) for x in args.plan_ids.split(",") if x.strip()}
        repairs = [r for r in repairs if int(r["plan_id"]) in want]

    counts = {
        "KEEP": 0,
        "UPDATE": 0,
        "CLEAR_UNSUPPORTED": 0,
        "MANUAL_REVIEW": 0,
        "unknown": 0,
    }
    sql_parts: list[str] = [
        "-- Generated by repair_membership_benefits.py",
        "-- Optimistic lock: WHERE plan_id AND updated_at = snapshot value",
        "BEGIN;",
        "",
    ]

    for item in repairs:
        action = item.get("action") or "unknown"
        counts[action] = counts.get(action, 0) + 1
        plan_id = int(item["plan_id"])
        old_b = item.get("old_benefits") or []
        new_b = item.get("new_benefits") or []
        if not isinstance(old_b, list):
            old_b = []
        if not isinstance(new_b, list):
            new_b = []
        d = diff_lists([str(x) for x in old_b], [str(x) for x in new_b])

        print(f"\n=== plan_id={plan_id} action={action} ===")
        print(f"reason: {item.get('reason', '')}")
        print(f"evidence: {item.get('evidence', '')}")
        if item.get("old_source_url") or item.get("new_source_url"):
            print(f"source: {item.get('old_source_url')} -> {item.get('new_source_url')}")
        print(f"removed ({len(d['removed'])}): {d['removed']}")
        print(f"added ({len(d['added'])}): {d['added']}")
        print(f"unchanged ({len(d['unchanged'])}): {d['unchanged']}")

        if action in ("UPDATE", "CLEAR_UNSUPPORTED"):
            snap = snap_idx.get(plan_id)
            if not snap:
                print(f"ERROR: plan {plan_id} missing from snapshot — skip SQL", file=sys.stderr)
                continue
            # CLEAR means empty benefits
            if action == "CLEAR_UNSUPPORTED":
                item = {**item, "new_benefits": item.get("new_benefits") or []}
            sql_parts.append(build_update_sql(item, snap))

    sql_parts.append("COMMIT;")
    sql_parts.append("")

    summary = {
        "total": len(repairs),
        "counts": counts,
        "sql_updates": sum(
            1
            for r in repairs
            if r.get("action") in ("UPDATE", "CLEAR_UNSUPPORTED")
        ),
    }
    print("\n" + json.dumps(summary, indent=2, ensure_ascii=False))

    if args.apply:
        args.sql_out.parent.mkdir(parents=True, exist_ok=True)
        args.sql_out.write_text("\n".join(sql_parts), encoding="utf-8")
        print(f"wrote SQL: {args.sql_out}")
        print(
            "NOTE: Apply via Supabase MCP execute_sql in batches; "
            "do not run BEGIN/COMMIT across MCP if unsupported — strip and run statements."
        )

    return 0


if __name__ == "__main__":
    sys.exit(main())
